/** 규칙 파서 테스트 — 담당: B */
import { describe, expect, it } from "vitest";
import { garam4 } from "@/lib/fixture";
import { parseAmounts, parseLines } from "@/lib/parse";

describe("parseLines", () => {
  it("기준 예시", () => {
    expect(parseLines(garam4.masked)).toEqual(garam4.parsed);
  });
});

type Case = [string, number[]];

function run(group: string, cases: Case[]) {
  describe(group, () => {
    for (const [text, expected] of cases) {
      it(`"${text}" → ${JSON.stringify(expected)}`, () => {
        expect(parseAmounts(text)).toEqual(expected);
      });
    }
  });
}

describe("parseAmounts", () => {
  // 구현계획서 4-1 금액 표기 예시 (뼈대에 있던 7개)
  run("기본 표기", [
    ["저녁 52,001원 냈어", [52001]],
    ["52001원", [52001]],
    ["아까 4만 8천 원이야", [48000]],
    ["4만8천", [48000]],
    ["3.5만 원", [35000]],
    ["택시 12,000원, 편의점 3,500원", [12000, 3500]],
    ["다들 조심히 들어가!", []],
  ]);

  run("숫자 + 원", [
    ["5000 원 냈어", [5000]],
    ["1인당 12,000원씩", [12000]],
    ["3개에 2천원", [2000]],
  ]);

  run("단위 (만·천)", [
    ["4만 8천원", [48000]],
    ["3.5만원", [35000]],
    ["3만원", [30000]],
    ["8천", [8000]],
    ["1만 2천 원", [12000]],
    ["만 원", [10000]],
    ["2천5백만원", [25000000]],
  ]);

  run("쉼표 천 단위만", [["총 12,000 나왔어", [12000]]]);

  run("한 줄에 여러 개", [["4만 8천 원이랑 3,000원", [48000, 3000]]]);

  // 부록 원문(02·05줄)과 가린 자리
  run("금액이 아닌 숫자", [
    ["2차 30,002원 내가 냈어. 가람·나·다온 셋이야", [30002]],
    ["다들 조심히 들어가! 내 번호 [전화번호]", []],
    ["[계좌번호]로 보내줘", []],
    ["4명이서 먹었어", []],
    ["9시 30분에 만나", []],
    ["오후 9:12 4만원", [40000]],
    ["52001", []],
  ]);

  // 확실하지 않은 표기는 읽지 않는다
  run("범위·잘못된 쉼표", [
    ["4, 5만원", []],
    ["3~4만원", []],
    ["3만원~4만원", []],
    ["1만천원", []],
    ["1,000,00원", []],
    ["12.000원", []],
  ]);
});
